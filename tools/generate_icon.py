"""Generates every version of the app icon from one drawing: four jigsaw pieces, one on its way in.

Writes the adaptive icon's vectors, the PNGs for Android 7 (which has no adaptive icons) and the
Play Store icon. Run from the project root after changing the design:

    python3 tools/generate_icon.py
"""
import math
from pathlib import Path

from PIL import Image, ImageDraw

BACKGROUND = "#14141C"
PINK, PURPLE, GREEN, ORANGE = "#EA4C89", "#7D6EF5", "#17C793", "#FFA63E"

SIZE = 18.5  # side of a piece, in the adaptive icon's 108 units
MIDDLE = 54
SHIFT = (-4, 4)  # the fitted pieces move aside, to leave room for the loose one
GAP = 0.5  # thin line between pieces, in the background's colour
CORNER = SIZE * 0.14

# Loose piece: rotated about a point, then moved towards the top right.
LOOSE_MOVE = (7.5, -7.5)
LOOSE_ANGLE = 7
LOOSE_PIVOT = (63.25, 40.75)

# Sides of a piece: top, right, bottom, left. 0 flat, 1 tab, -1 notch. Each shared side is one curve.
PIECES = [
    {"cell": (0, 0), "sides": (0, 1, -1, 0), "colour": PINK, "alpha": 1.0, "loose": False},
    {"cell": (1, 0), "sides": (0, 0, 1, -1), "colour": PURPLE, "alpha": 0.8, "loose": True},
    {"cell": (0, 1), "sides": (1, -1, 0, 0), "colour": GREEN, "alpha": 0.65, "loose": False},
    {"cell": (1, 1), "sides": (-1, 0, 0, 1), "colour": ORANGE, "alpha": 0.45, "loose": False},
]

DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
SUPERSAMPLE = 4

# Adaptive icons show only the central 72 of their 108 units: the rest is there for launcher effects.
VISIBLE = 72
VISIBLE_START = (108 - VISIBLE) / 2


def edge_commands(start, end, side):
    """Path commands from start to end: a straight line, or a jigsaw tab or notch in the middle."""
    x0, y0 = start
    x1, y1 = end
    if side == 0:
        return [("L", [end])]

    dx, dy = x1 - x0, y1 - y0
    nx, ny = dy * side, -dx * side  # outward normal of a clockwise path, scaled by the side's length

    def at(along, out):
        return (round(x0 + dx * along + nx * out, 2), round(y0 + dy * along + ny * out, 2))

    return [
        ("L", [at(0.36, 0)]),
        ("C", [at(0.41, 0), at(0.43, 0.04), at(0.41, 0.09)]),
        ("C", [at(0.37, 0.2), at(0.4, 0.29), at(0.5, 0.29)]),
        ("C", [at(0.6, 0.29), at(0.63, 0.2), at(0.59, 0.09)]),
        ("C", [at(0.57, 0.04), at(0.59, 0), at(0.64, 0)]),
        ("L", [end]),
    ]


def piece_commands(piece):
    col, row = piece["cell"]
    sides = piece["sides"]
    x = MIDDLE + SHIFT[0] + (col - 1) * SIZE
    y = MIDDLE + SHIFT[1] + (row - 1) * SIZE
    corners = [(x, y), (x + SIZE, y), (x + SIZE, y + SIZE), (x, y + SIZE)]

    def rounded(i):
        return sides[i] == 0 and sides[(i + 3) % 4] == 0

    def near(a, b):
        distance = math.hypot(b[0] - a[0], b[1] - a[1])
        return (a[0] + (b[0] - a[0]) * CORNER / distance, a[1] + (b[1] - a[1]) * CORNER / distance)

    start = near(corners[0], corners[1]) if rounded(0) else corners[0]
    commands = [("M", [start])]

    for i in range(4):
        following = (i + 1) % 4
        begin = near(corners[i], corners[following]) if rounded(i) else corners[i]
        end = near(corners[following], corners[i]) if rounded(following) else corners[following]
        commands += edge_commands(begin, end, sides[i])
        if rounded(following):
            commands.append(("Q", [corners[following], near(corners[following], corners[(following + 1) % 4])]))

    commands.append(("Z", []))
    return commands


def path_data(commands):
    def number(value):
        return f"{value:.2f}".rstrip("0").rstrip(".")

    return "".join(
        name + " ".join(f"{number(x)},{number(y)}" for x, y in points) for name, points in commands
    )


def vector(body):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/generate_icon.py: change the design there. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        '    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n'
        f"{body}"
        "</vector>\n"
    )


def path_tag(commands, attributes):
    lines = [f'android:{name}="{value}"' for name, value in attributes.items()]
    lines.append(f'android:pathData="{path_data(commands)}"')
    return "<path\n        " + "\n        ".join(lines) + " />\n"


def with_loose_transform(tag):
    return (
        f'    <group\n        android:translateX="{LOOSE_MOVE[0]}"\n        android:translateY="{LOOSE_MOVE[1]}"\n'
        f'        android:rotation="{LOOSE_ANGLE}"\n        android:pivotX="{LOOSE_PIVOT[0]}"\n'
        f'        android:pivotY="{LOOSE_PIVOT[1]}">\n        {tag}    </group>\n'
    )


def foreground_xml():
    body = ""
    for piece in PIECES:
        tag = path_tag(
            piece_commands(piece),
            {
                "fillColor": piece["colour"],
                "strokeColor": BACKGROUND,
                "strokeWidth": GAP,
                "strokeLineJoin": "round",
            },
        )
        body += with_loose_transform(tag) if piece["loose"] else "    " + tag
    return vector(body)


def monochrome_xml():
    """Android 13 tints this with one colour, so pieces are told apart by opacity, not by a gap."""
    body = ""
    for piece in PIECES:
        tag = path_tag(piece_commands(piece), {"fillColor": "#FFFFFF", "fillAlpha": piece["alpha"]})
        body += with_loose_transform(tag) if piece["loose"] else "    " + tag
    return vector(body)


def background_xml():
    return vector(f'    <path\n        android:fillColor="{BACKGROUND}"\n        android:pathData="M0,0h108v108h-108z" />\n')


def flatten(commands, steps=24):
    """Points along a path, in the 108-unit space."""
    points = []
    for name, args in commands:
        if name in ("M", "L"):
            points.append(args[0])
        elif name == "Q":
            p0, p1, p2 = points[-1], args[0], args[1]
            for i in range(1, steps + 1):
                t = i / steps
                points.append(tuple((1 - t) ** 2 * p0[k] + 2 * (1 - t) * t * p1[k] + t * t * p2[k] for k in (0, 1)))
        elif name == "C":
            p0, p1, p2, p3 = points[-1], args[0], args[1], args[2]
            for i in range(1, steps + 1):
                t = i / steps
                u = 1 - t
                points.append(
                    tuple(u**3 * p0[k] + 3 * u * u * t * p1[k] + 3 * u * t * t * p2[k] + t**3 * p3[k] for k in (0, 1))
                )
    return points


def moved_loose(point):
    angle = math.radians(LOOSE_ANGLE)
    x, y = point[0] - LOOSE_PIVOT[0], point[1] - LOOSE_PIVOT[1]
    return (
        x * math.cos(angle) - y * math.sin(angle) + LOOSE_PIVOT[0] + LOOSE_MOVE[0],
        x * math.sin(angle) + y * math.cos(angle) + LOOSE_PIVOT[1] + LOOSE_MOVE[1],
    )


def artwork(size):
    """The visible part of the adaptive icon, as a full square image."""
    image = Image.new("RGBA", (size, size), BACKGROUND)
    draw = ImageDraw.Draw(image)
    scale = size / VISIBLE

    for piece in PIECES:
        points = flatten(piece_commands(piece))
        if piece["loose"]:
            points = [moved_loose(p) for p in points]
        pixels = [((x - VISIBLE_START) * scale, (y - VISIBLE_START) * scale) for x, y in points]
        draw.polygon(pixels, fill=piece["colour"])
        draw.line(pixels + pixels[:2], fill=BACKGROUND, width=max(1, round(GAP * scale)), joint="curve")

    return image


def masked(image, shape):
    mask = Image.new("L", image.size, 0)
    draw = ImageDraw.Draw(mask)
    box = (0, 0, image.width - 1, image.height - 1)
    if shape == "round":
        draw.ellipse(box, fill=255)
    else:
        draw.rounded_rectangle(box, radius=image.width * 0.22, fill=255)

    result = Image.new("RGBA", image.size, (0, 0, 0, 0))
    result.paste(image, (0, 0), mask)
    return result


res = Path("app/src/main/res")
(res / "drawable/ic_launcher_foreground.xml").write_text(foreground_xml())
(res / "drawable/ic_launcher_monochrome.xml").write_text(monochrome_xml())
(res / "drawable/ic_launcher_background.xml").write_text(background_xml())

for density, size in DENSITIES.items():
    big = artwork(size * SUPERSAMPLE)
    folder = res / f"mipmap-{density}"
    masked(big, "square").resize((size, size), Image.LANCZOS).save(folder / "ic_launcher.png")
    masked(big, "round").resize((size, size), Image.LANCZOS).save(folder / "ic_launcher_round.png")

# Google Play applies its own mask, and asks for a full square with no transparency.
artwork(512 * SUPERSAMPLE).resize((512, 512), Image.LANCZOS).convert("RGB").save("docs/store/icon-512.png")
