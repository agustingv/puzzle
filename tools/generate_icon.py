"""Generates every version of the app icon from one drawing: a white jigsaw piece on a pink to lilac gradient.

Writes the adaptive icon's vectors, the PNGs for Android 7 (which has no adaptive icons) and the
Play Store icon. Run from the project root after changing the design:

    python3 tools/generate_icon.py
"""
import math
from pathlib import Path

from PIL import Image, ImageDraw

# The gradient of the games' icons, from the top left corner to the bottom right one.
GRADIENT = ("#F0609A", "#7D6EF5")
PIECE = "#FFFFFF"
SHADOW = "#2A1E52"
SHADOW_ALPHA = 0.18
SHADOW_OFFSET = (1.2, 2)

# One piece, in the adaptive icon's 108 units: a tab on top and on the right, a notch below and on the left.
SIZE = 36
CORNER = SIZE * 0.14
ORIGIN = (33, 39)
SIDES = (1, 1, -1, -1)  # top, right, bottom, left. 0 flat, 1 tab, -1 notch.
# The tabs make the piece's box larger than its body: centred by its area, not by its box, the body sits in
# the middle and the piece looks centred, also inside a round mask.
CENTRE_SHIFT = (1.07, -1.07)

DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
SUPERSAMPLE = 4

# Adaptive icons show only the central 72 of their 108 units: the rest is there for launcher effects.
VISIBLE = 72
VISIBLE_START = (108 - VISIBLE) / 2


def edge_commands(start, end, side):
    """Path commands from start to end: a straight line, or a jigsaw tab or notch in the middle."""
    x0, y0 = start
    x1, y1 = end
    if side == 0:
        return [("L", [end])]

    dx, dy = x1 - x0, y1 - y0
    nx, ny = dy * side, -dx * side  # outward normal of a clockwise path, scaled by the side's length

    def at(along, out):
        return (round(x0 + dx * along + nx * out, 2), round(y0 + dy * along + ny * out, 2))

    return [
        ("L", [at(0.36, 0)]),
        ("C", [at(0.41, 0), at(0.43, 0.04), at(0.41, 0.09)]),
        ("C", [at(0.37, 0.2), at(0.4, 0.29), at(0.5, 0.29)]),
        ("C", [at(0.6, 0.29), at(0.63, 0.2), at(0.59, 0.09)]),
        ("C", [at(0.57, 0.04), at(0.59, 0), at(0.64, 0)]),
        ("L", [end]),
    ]


def piece_commands():
    x, y = ORIGIN
    corners = [(x, y), (x + SIZE, y), (x + SIZE, y + SIZE), (x, y + SIZE)]

    def rounded(i):
        return SIDES[i] == 0 and SIDES[(i + 3) % 4] == 0

    def near(a, b):
        distance = math.hypot(b[0] - a[0], b[1] - a[1])
        return (a[0] + (b[0] - a[0]) * CORNER / distance, a[1] + (b[1] - a[1]) * CORNER / distance)

    start = near(corners[0], corners[1]) if rounded(0) else corners[0]
    commands = [("M", [start])]

    for i in range(4):
        following = (i + 1) % 4
        begin = near(corners[i], corners[following]) if rounded(i) else corners[i]
        end = near(corners[following], corners[i]) if rounded(following) else corners[following]
        commands += edge_commands(begin, end, SIDES[i])
        if rounded(following):
            commands.append(("Q", [corners[following], near(corners[following], corners[(following + 1) % 4])]))

    commands.append(("Z", []))
    return commands


def path_data(commands):
    def number(value):
        return f"{value:.2f}".rstrip("0").rstrip(".")

    return "".join(
        name + " ".join(f"{number(x)},{number(y)}" for x, y in points) for name, points in commands
    )


def vector(body, aapt=False):
    namespace = '\n    xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/generate_icon.py: change the design there. -->\n"
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{namespace}\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        '    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n'
        f"{body}"
        "</vector>\n"
    )


def centred(body, extra=(0, 0)):
    return (
        f'    <group\n        android:translateX="{CENTRE_SHIFT[0] + extra[0]:g}"\n'
        f'        android:translateY="{CENTRE_SHIFT[1] + extra[1]:g}">\n{body}    </group>\n'
    )


def piece_tag(colour, alpha=1.0):
    alpha_line = f'\n            android:fillAlpha="{alpha:g}"' if alpha < 1 else ""
    return (
        f'        <path\n            android:fillColor="{colour}"{alpha_line}\n'
        f'            android:pathData="{path_data(piece_commands())}" />\n'
    )


def foreground_xml():
    return vector(centred(piece_tag(SHADOW, SHADOW_ALPHA), SHADOW_OFFSET) + centred(piece_tag(PIECE)))


def monochrome_xml():
    """Android 13 tints this with one colour: the piece alone."""
    return vector(centred(piece_tag("#FFFFFF")))


def background_xml():
    start, end = GRADIENT
    return vector(
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient\n'
        '                android:type="linear"\n'
        '                android:startX="0"\n'
        '                android:startY="0"\n'
        '                android:endX="108"\n'
        '                android:endY="108">\n'
        f'                <item android:offset="0" android:color="#FF{start[1:]}" />\n'
        f'                <item android:offset="1" android:color="#FF{end[1:]}" />\n'
        '            </gradient>\n'
        '        </aapt:attr>\n'
        '    </path>\n',
        aapt=True,
    )


def flatten(commands, steps=24):
    """Points along a path, in the 108-unit space."""
    points = []
    for name, args in commands:
        if name in ("M", "L"):
            points.append(args[0])
        elif name == "Q":
            p0, p1, p2 = points[-1], args[0], args[1]
            for i in range(1, steps + 1):
                t = i / steps
                points.append(tuple((1 - t) ** 2 * p0[k] + 2 * (1 - t) * t * p1[k] + t * t * p2[k] for k in (0, 1)))
        elif name == "C":
            p0, p1, p2, p3 = points[-1], args[0], args[1], args[2]
            for i in range(1, steps + 1):
                t = i / steps
                u = 1 - t
                points.append(
                    tuple(u**3 * p0[k] + 3 * u * u * t * p1[k] + 3 * u * t * t * p2[k] + t**3 * p3[k] for k in (0, 1))
                )
    return points


def rgb(colour):
    return tuple(int(colour[i:i + 2], 16) for i in (1, 3, 5))


def artwork(size):
    """The visible part of the adaptive icon, as a full square image."""
    scale = size / VISIBLE

    # The gradient runs along the diagonal of the whole 108 units, of which only the middle shows.
    start, end = rgb(GRADIENT[0]), rgb(GRADIENT[1])
    ramp = Image.new("RGB", (size, size))
    pixels = ramp.load()
    for y in range(size):
        for x in range(size):
            t = ((x / scale + VISIBLE_START) + (y / scale + VISIBLE_START)) / 216
            pixels[x, y] = tuple(round(a + (b - a) * t) for a, b in zip(start, end))
    image = ramp.convert("RGBA")

    def polygon(shift):
        dx, dy = CENTRE_SHIFT[0] + shift[0], CENTRE_SHIFT[1] + shift[1]
        return [((x + dx - VISIBLE_START) * scale, (y + dy - VISIBLE_START) * scale) for x, y in flatten(piece_commands())]

    shadow = Image.new("RGBA", image.size, (*rgb(SHADOW), 0))
    ImageDraw.Draw(shadow).polygon(polygon(SHADOW_OFFSET), fill=(*rgb(SHADOW), round(255 * SHADOW_ALPHA)))
    image = Image.alpha_composite(image, shadow)
    ImageDraw.Draw(image).polygon(polygon((0, 0)), fill=PIECE)
    return image


def masked(image, shape):
    mask = Image.new("L", image.size, 0)
    draw = ImageDraw.Draw(mask)
    box = (0, 0, image.width - 1, image.height - 1)
    if shape == "round":
        draw.ellipse(box, fill=255)
    else:
        draw.rounded_rectangle(box, radius=image.width * 0.22, fill=255)

    result = Image.new("RGBA", image.size, (0, 0, 0, 0))
    result.paste(image, (0, 0), mask)
    return result


res = Path("app/src/main/res")
(res / "drawable/ic_launcher_foreground.xml").write_text(foreground_xml())
(res / "drawable/ic_launcher_monochrome.xml").write_text(monochrome_xml())
(res / "drawable/ic_launcher_background.xml").write_text(background_xml())

for density, size in DENSITIES.items():
    big = artwork(size * SUPERSAMPLE)
    folder = res / f"mipmap-{density}"
    masked(big, "square").resize((size, size), Image.LANCZOS).save(folder / "ic_launcher.png")
    masked(big, "round").resize((size, size), Image.LANCZOS).save(folder / "ic_launcher_round.png")

# Google Play applies its own mask, and asks for a full square with no transparency.
artwork(512 * SUPERSAMPLE).resize((512, 512), Image.LANCZOS).convert("RGB").save("docs/store/icon-512.png")
